#!/usr/bin/env bash
#
# mkweb.sh -- turn a folder of original photos into a publishable gallery.
#
#   tools/mkweb.sh <source-dir> <gallery-name> ["Gallery Title"]
#
# Generates, into assets/photography/<gallery-name>/ :
#   <base>-thumbnail.jpg        grid thumbnail
#   <base>-<W>x<H>.jpg          one per ladder rung that the source can fill
# and writes _data/galleries/<gallery-name>.yml with `sizes:` in ascending
# order, which is what the lightbox depends on.
#
# Originals are NOT copied into the repository -- only the derivatives are, and
# .gitignore whitelists exactly the sizes named below. Keep the two in sync.
#
# Requires only `sips` (ships with macOS).

set -euo pipefail

THUMB_LONG=600
LADDER=(1000 1600 2800)

die() { printf 'mkweb: %s\n' "$*" >&2; exit 1; }

[ $# -ge 2 ] || die "usage: tools/mkweb.sh <source-dir> <gallery-name> [\"Title\"]"

SRC_DIR="${1%/}"
GALLERY="$2"
TITLE="${3:-$2}"

[ -d "$SRC_DIR" ] || die "source directory not found: $SRC_DIR"

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT_DIR="$REPO_ROOT/assets/photography/$GALLERY"
YAML="$REPO_ROOT/_data/galleries/$GALLERY.yml"

mkdir -p "$OUT_DIR" "$REPO_ROOT/_data/galleries"

# Long edge of an image, in pixels.
long_edge() {
  sips -g pixelWidth -g pixelHeight "$1" \
    | awk '/pixelWidth/{w=$2} /pixelHeight/{h=$2} END{print (w>h)?w:h}'
}

# "WxH" of an image.
dims() {
  sips -g pixelWidth -g pixelHeight "$1" \
    | awk '/pixelWidth/{w=$2} /pixelHeight/{h=$2} END{printf "%sx%s", w, h}'
}

# Collect sources (case-insensitive extensions, stable order).
shopt -s nullglob nocaseglob
sources=("$SRC_DIR"/*.jpg "$SRC_DIR"/*.jpeg "$SRC_DIR"/*.png "$SRC_DIR"/*.tif "$SRC_DIR"/*.tiff)
shopt -u nocaseglob
[ ${#sources[@]} -gt 0 ] || die "no images found in $SRC_DIR"
IFS=$'\n' sources=($(printf '%s\n' "${sources[@]}" | sort)); unset IFS

printf 'Gallery "%s": %d source image(s)\n' "$GALLERY" "${#sources[@]}"

# --- derivatives -------------------------------------------------------------

declare -a yaml_entries=()
smallest_source=999999

for src in "${sources[@]}"; do
  base="$(basename "$src")"; base="${base%.*}"

  # Jekyll silently refuses to copy any file whose name begins with `_`, `.`
  # or `#`. Nikon writes Adobe-RGB frames as `_DSC1234.jpg`, so leaving the
  # leading underscore in place yields a GREEN build with every image 404ing
  # in production. Strip reserved leading characters, and any other character
  # that has no business in a URL.
  base="$(printf '%s' "$base" | sed -E 's/^[_.#]+//; s/[^A-Za-z0-9._-]+/-/g')"
  [ -n "$base" ] || die "$src: filename reduces to nothing after sanitising"

  src_long="$(long_edge "$src")"
  [ "$src_long" -lt "$smallest_source" ] && smallest_source="$src_long"

  printf '  %-24s source long edge %spx\n' "$base" "$src_long"

  # Thumbnail. Never upscale: if the source is smaller than the thumb target,
  # the source size is the best we can do.
  thumb_target=$(( THUMB_LONG < src_long ? THUMB_LONG : src_long ))
  sips -Z "$thumb_target" -s format jpeg "$src" \
       --out "$OUT_DIR/$base-thumbnail.jpg" >/dev/null

  # Display ladder. Name each file AFTER measuring it -- the second dimension
  # is a rounded value that cannot be predicted, and the template parses the
  # real width back out of the filename to build the srcset.
  sizes=()
  for rung in "${LADDER[@]}"; do
    if [ "$rung" -gt "$src_long" ]; then
      printf '    skip %spx (would upscale)\n' "$rung"
      continue
    fi
    tmp="$OUT_DIR/.$base-tmp.jpg"
    sips -Z "$rung" -s format jpeg "$src" --out "$tmp" >/dev/null
    d="$(dims "$tmp")"
    mv "$tmp" "$OUT_DIR/$base-$d.jpg"
    sizes+=("$base-$d.jpg")
    printf '    %s\n' "$base-$d.jpg"
  done

  [ ${#sizes[@]} -gt 0 ] || die "$base: source is smaller than every ladder rung (${LADDER[*]}px); nothing to publish"

  entry="- filename: $base"$'\n'
  entry+="  sizes:"$'\n'
  for s in "${sizes[@]}"; do entry+="  - $s"$'\n'; done
  entry+="  thumbnail: $base-thumbnail.jpg"
  yaml_entries+=("$entry")
done

# --- gallery data file -------------------------------------------------------

first_base="$(basename "${sources[0]}")"; first_base="${first_base%.*}"
first_base="$(printf '%s' "$first_base" | sed -E 's/^[_.#]+//; s/[^A-Za-z0-9._-]+/-/g')"
first_sizes=()
for f in "$OUT_DIR/$first_base"-*x*.jpg; do first_sizes+=("$(basename "$f")"); done
IFS=$'\n' first_sizes=($(printf '%s\n' "${first_sizes[@]}" | sort -t'-' -k2 -V)); unset IFS

{
  echo "# Generated by tools/mkweb.sh -- re-run it rather than editing by hand."
  echo "# \`sizes\` MUST stay in ascending order: the lightbox opens \`sizes | last\`."
  echo "picture_path: $GALLERY"
  echo "preview:"
  echo "  filename: $first_base"
  echo "  sizes:"
  for s in "${first_sizes[@]}"; do echo "  - $s"; done
  echo "  thumbnail: $first_base-thumbnail.jpg"
  echo "pictures:"
  for e in "${yaml_entries[@]}"; do echo "$e"; done
} > "$YAML"

# --- guards: derivatives must be both publishable and committable ------------

# Jekyll drops files starting with _ . or # without saying anything.
bad_names="$(find "$OUT_DIR" -name '[_.#]*.jpg' -print)"
if [ -n "$bad_names" ]; then
  printf '%s\n' "$bad_names" >&2
  die "the above filenames start with a character Jekyll excludes from the build"
fi

if git -C "$REPO_ROOT" rev-parse --git-dir >/dev/null 2>&1; then
  ignored=0
  while IFS= read -r f; do
    if git -C "$REPO_ROOT" check-ignore -q "$f"; then
      printf '  WARNING: .gitignore excludes %s\n' "${f#"$REPO_ROOT/"}" >&2
      ignored=1
    fi
  done < <(find "$OUT_DIR" -name '*.jpg')
  [ "$ignored" -eq 0 ] || die "some derivatives are gitignored -- add their sizes to the .gitignore whitelist"
fi

printf '\nWrote %s\n' "${YAML#"$REPO_ROOT/"}"
printf 'Next: add an entry to _data/galleries/overview.yml and create photography/%s.md\n' "$GALLERY"

if [ "$smallest_source" -lt 1600 ]; then
  printf '\nNOTE: smallest source long edge is %spx, so the larger ladder rungs were\n' "$smallest_source"
  printf '      skipped. Supply full-resolution originals and re-run to publish\n'
  printf '      sharper images for high-DPI screens.\n'
fi
